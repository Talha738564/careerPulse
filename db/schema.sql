-- Oracle Database 19c+; run once in an EMPTY course-project schema.
-- Identity values start at 1000 so explicit educational seed IDs do not collide.
-- USERS
CREATE TABLE users (
  user_id        NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 1000) PRIMARY KEY,
  full_name      VARCHAR2(120) NOT NULL,
  email          VARCHAR2(150) NOT NULL UNIQUE,
  password_hash  VARCHAR2(255) NOT NULL,
  role           VARCHAR2(20) NOT NULL CHECK (role IN ('STUDENT','ADMIN')),
  created_at     DATE DEFAULT SYSDATE NOT NULL,
  is_active      CHAR(1) DEFAULT 'Y' NOT NULL CHECK (is_active IN ('Y','N'))
);

-- STUDENTS
CREATE TABLE students (
  student_id     NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 1000) PRIMARY KEY,
  user_id        NUMBER NOT NULL UNIQUE REFERENCES users(user_id),
  university     VARCHAR2(150),
  major          VARCHAR2(120),
  study_year     NUMBER,
  cgpa           NUMBER(4,2),
  city           VARCHAR2(100),
  resume_url     VARCHAR2(500),
  portfolio_url  VARCHAR2(500),
  bio            VARCHAR2(1000)
);

-- SKILLS
CREATE TABLE skills (
  skill_id       NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 1000) PRIMARY KEY,
  skill_name     VARCHAR2(100) NOT NULL UNIQUE,
  category       VARCHAR2(80)
);

-- STUDENT_SKILLS
CREATE TABLE student_skills (
  student_skill_id NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 1000) PRIMARY KEY,
  student_id       NUMBER NOT NULL REFERENCES students(student_id),
  skill_id         NUMBER NOT NULL REFERENCES skills(skill_id),
  proficiency      VARCHAR2(20) DEFAULT 'BEGINNER'
                   CHECK (proficiency IN ('BEGINNER','INTERMEDIATE','ADVANCED')),
  years_experience NUMBER(3,1) DEFAULT 0,
  CONSTRAINT uq_student_skill UNIQUE (student_id, skill_id)
);

-- COMPANIES
CREATE TABLE companies (
  company_id       NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 1000) PRIMARY KEY,
  company_name     VARCHAR2(150) NOT NULL,
  industry         VARCHAR2(100),
  website_url      VARCHAR2(500),
  careers_page_url VARCHAR2(500),
  city             VARCHAR2(100),
  is_verified      CHAR(1) DEFAULT 'N' NOT NULL CHECK (is_verified IN ('Y','N')),
  description      VARCHAR2(2000)
);

-- OPPORTUNITIES
CREATE TABLE opportunities (
  opp_id            NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 1000) PRIMARY KEY,
  company_id        NUMBER NOT NULL REFERENCES companies(company_id),
  title             VARCHAR2(200) NOT NULL,
  job_type          VARCHAR2(20) NOT NULL
                    CHECK (job_type IN ('INTERNSHIP','FREELANCE','FULL_TIME')),
  description       VARCHAR2(4000),
  requirements      VARCHAR2(4000),
  city              VARCHAR2(100),
  is_remote         CHAR(1) DEFAULT 'N' NOT NULL CHECK (is_remote IN ('Y','N')),
  min_salary        NUMBER(12,2),
  max_salary        NUMBER(12,2),
  experience_level  VARCHAR2(30)
                    CHECK (experience_level IN ('STUDENT','FRESH','JUNIOR')),
  apply_url         VARCHAR2(500),
  source_name       VARCHAR2(150),
  posted_at         DATE DEFAULT SYSDATE NOT NULL,
  deadline          DATE,
  status            VARCHAR2(20) DEFAULT 'ACTIVE'
                    CHECK (status IN ('ACTIVE','EXPIRED','REMOVED'))
);

-- OPPORTUNITY_SKILLS
CREATE TABLE opportunity_skills (
  opp_skill_id  NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 1000) PRIMARY KEY,
  opp_id        NUMBER NOT NULL REFERENCES opportunities(opp_id),
  skill_id      NUMBER NOT NULL REFERENCES skills(skill_id),
  importance    VARCHAR2(20) DEFAULT 'REQUIRED'
                CHECK (importance IN ('REQUIRED','PREFERRED')),
  CONSTRAINT uq_opp_skill UNIQUE (opp_id, skill_id)
);

-- SAVED_JOBS
CREATE TABLE saved_jobs (
  saved_id    NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 1000) PRIMARY KEY,
  student_id  NUMBER NOT NULL REFERENCES students(student_id),
  opp_id      NUMBER NOT NULL REFERENCES opportunities(opp_id),
  saved_at    DATE DEFAULT SYSDATE NOT NULL,
  CONSTRAINT uq_saved_job UNIQUE (student_id, opp_id)
);

-- APPLICATION_TRACKER
CREATE TABLE application_tracker (
  tracking_id   NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 1000) PRIMARY KEY,
  student_id    NUMBER NOT NULL REFERENCES students(student_id),
  opp_id        NUMBER NOT NULL REFERENCES opportunities(opp_id),
  status        VARCHAR2(20) NOT NULL DEFAULT 'SAVED'
                CHECK (status IN ('SAVED','APPLIED','INTERVIEW','OFFER','REJECTED')),
  applied_on    DATE,
  notes         VARCHAR2(1000),
  last_updated  DATE DEFAULT SYSDATE NOT NULL,
  CONSTRAINT uq_tracker_student_opp UNIQUE (student_id, opp_id)
);

-- JOB_ALERTS
CREATE TABLE job_alerts (
  alert_id       NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 1000) PRIMARY KEY,
  student_id     NUMBER NOT NULL REFERENCES students(student_id),
  alert_name     VARCHAR2(150) NOT NULL,
  city           VARCHAR2(100),
  is_remote_only CHAR(1) DEFAULT 'N' NOT NULL CHECK (is_remote_only IN ('Y','N')),
  job_type       VARCHAR2(20)
                 CHECK (job_type IN ('INTERNSHIP','FREELANCE','FULL_TIME')),
  min_salary     NUMBER(12,2),
  created_at     DATE DEFAULT SYSDATE NOT NULL,
  is_active      CHAR(1) DEFAULT 'Y' NOT NULL CHECK (is_active IN ('Y','N'))
);

-- JOB_ALERT_SKILLS
CREATE TABLE job_alert_skills (
  alert_skill_id NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 1000) PRIMARY KEY,
  alert_id       NUMBER NOT NULL REFERENCES job_alerts(alert_id),
  skill_id       NUMBER NOT NULL REFERENCES skills(skill_id),
  CONSTRAINT uq_alert_skill UNIQUE (alert_id, skill_id)
);

-- NOTIFICATIONS
CREATE TABLE notifications (
  notification_id  NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 1000) PRIMARY KEY,
  user_id          NUMBER NOT NULL REFERENCES users(user_id),
  opp_id           NUMBER REFERENCES opportunities(opp_id),
  title            VARCHAR2(200) NOT NULL,
  message          VARCHAR2(1000) NOT NULL,
  notification_type VARCHAR2(30) NOT NULL
                   CHECK (notification_type IN ('NEW_MATCH','DEADLINE_SOON','SYSTEM')),
  is_read          CHAR(1) DEFAULT 'N' NOT NULL CHECK (is_read IN ('Y','N')),
  created_at       DATE DEFAULT SYSDATE NOT NULL
);

-- APPLY_CLICKS
CREATE TABLE apply_clicks (
  click_id   NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 1000) PRIMARY KEY,
  student_id NUMBER NOT NULL REFERENCES students(student_id),
  opp_id     NUMBER NOT NULL REFERENCES opportunities(opp_id),
  clicked_at DATE DEFAULT SYSDATE NOT NULL
);

-- SKILL_RESOURCES
CREATE TABLE skill_resources (
  resource_id    NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 1000) PRIMARY KEY,
  skill_id       NUMBER NOT NULL REFERENCES skills(skill_id),
  resource_title VARCHAR2(200) NOT NULL,
  resource_url   VARCHAR2(500) NOT NULL,
  resource_type  VARCHAR2(30)
                 CHECK (resource_type IN ('COURSE','YOUTUBE','DOCUMENTATION','ARTICLE')),
  difficulty     VARCHAR2(20)
                 CHECK (difficulty IN ('BEGINNER','INTERMEDIATE','ADVANCED'))
);

-- Extensions support explicit demo links and safe lifecycle management.
ALTER TABLE companies ADD (is_active CHAR(1) DEFAULT 'Y' NOT NULL CHECK (is_active IN ('Y','N')));
ALTER TABLE opportunities ADD (
  is_demo CHAR(1) DEFAULT 'Y' NOT NULL CHECK (is_demo IN ('Y','N')),
  is_verified CHAR(1) DEFAULT 'N' NOT NULL CHECK (is_verified IN ('Y','N')),
  CONSTRAINT ck_real_apply CHECK (is_demo = 'Y' OR apply_url IS NOT NULL),
  CONSTRAINT ck_demo_unverified CHECK (is_demo = 'N' OR is_verified = 'N'),
  CONSTRAINT ck_salary_range CHECK (min_salary >= 0 AND max_salary >= min_salary)
);
ALTER TABLE students ADD CONSTRAINT ck_study_year CHECK (study_year BETWEEN 1 AND 8);
ALTER TABLE students ADD CONSTRAINT ck_cgpa CHECK (cgpa BETWEEN 0 AND 4);
ALTER TABLE student_skills ADD CONSTRAINT ck_experience CHECK (years_experience BETWEEN 0 AND 50);
ALTER TABLE application_tracker ADD CONSTRAINT ck_applied_date CHECK (status = 'SAVED' OR applied_on IS NOT NULL);
ALTER TABLE job_alerts ADD CONSTRAINT ck_alert_salary CHECK (min_salary >= 0);
ALTER TABLE notifications ADD (event_key VARCHAR2(200));
ALTER TABLE notifications ADD CONSTRAINT uq_notice_event UNIQUE (user_id, event_key);
CREATE UNIQUE INDEX uq_user_email_normalized ON users (LOWER(email));
CREATE INDEX ix_opp_status_deadline ON opportunities(status, deadline);
CREATE INDEX ix_opp_city ON opportunities(city);
CREATE INDEX ix_opp_skill ON opportunity_skills(skill_id);
CREATE INDEX ix_student_skill ON student_skills(skill_id);
CREATE INDEX ix_notice_user_read ON notifications(user_id, is_read);
CREATE INDEX ix_opp_company ON opportunities(company_id);
CREATE INDEX ix_tracker_opp ON application_tracker(opp_id);
CREATE INDEX ix_saved_opp ON saved_jobs(opp_id);
